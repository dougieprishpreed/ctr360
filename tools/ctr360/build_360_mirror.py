def replace_define_block(text, name, new_body):
    old, s, e = find_define_block(text, name)
    eol = "\r\n" if "\r\n" in old else "\n"
    return text[:s] + new_body + eol + text[e:]

def strip_define_designators(text, name):
    """Remove leading `.field =` / `[idx] =` designators on every line of a macro body."""
    old, s, e = find_define_block(text, name)
    out = []
    for ln in old.splitlines(keepends=True):
        ln = re.sub(r"^([ \t]*)\.[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*", r"\1", ln)
        ln = re.sub(r"^([ \t]*)\[[^\]]*\][ \t]*=[ \t]*", r"\1", ln)
        out.append(ln)
    new = "".join(out)
    if re.search(r"^[ \t]*\.[A-Za-z_][A-Za-z0-9_]*[ \t]*=", new, re.M):
        raise RuntimeError("designator remains in macro " + name)
    return text[:s] + new + text[e:]


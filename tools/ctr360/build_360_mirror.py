def _block_for_marker(t, field_marker, close_marker):
    """(start, end) of the struct block containing field_marker and closing
    at close_marker; end includes the trailing newline."""
    fi = t.find(field_marker)
    if fi < 0:
        return None
    st = t.rfind("\t\tstruct", 0, fi)
    if st < 0:
        return None
    en = t.find(close_marker, fi)
    if en < 0:
        return None
    en += len(close_marker)
    if t[en:en + 2] == "\r\n":
        en += 2
    elif t[en:en + 1] == "\n":
        en += 1
    return st, en

def apply_member_swaps(mirror, log):
    """Swap union member blocks so the overwhelmingly-designated member
    becomes the first member (positionally expressible in C89)."""
    for path, m_a, close_a, m_b, close_b, note in MEMBER_SWAPS:
        p = os.path.join(mirror, path)
        t = b2s(read_bytes(p))
        sa = _block_for_marker(t, m_a, close_a)
        sb = _block_for_marker(t, m_b, close_b)
        if not sa or not sb or not (sa[1] <= sb[0]):
            raise RuntimeError("member swap markers not found/ordered in " + path)
        t2 = t[:sa[0]] + t[sb[0]:sb[1]] + t[sa[1]:sb[0]] + t[sa[0]:sa[1]] + t[sb[1]:]
        write_bytes(p, s2b(t2))
        log("patched %s: union member swap (%s)" % (path, note))


#!/usr/bin/env python3
"""build_360_mirror.py - generate an XDK/MSVC-2010-compatible mirror of the CTR game sources.

Pipeline (offline, deterministic):
  1. copy  <root>/game  and  <root>/include  into  <out> (the mirror)
  2. apply hand-verified macro/struct patches (designated -> positional macro bodies)
     + PrimCode field reorder (raw `code` byte first, zero ABI effect, lets
       positional init express `.code = X`)
  3. clang semantic-AST JSON dump per parse unit, run against the *mirror*
  4. rewrite all remaining designated initializers to positional form
     (clang already resolved designators to positional slots in its semantic AST;
      ImplicitValueInitExpr marks skipped slots; macro children are re-expanded
      to braces, which is valid in initializer context)
  5. scan for leftovers, write _transform_report.json, print summary

Rationale: the Xbox 360 XDK compiler (cl 16.00, VS2010-era) rejects C99
designated initializers, which the decompiled sources use heavily. This tool
produces sources the XDK toolchain accepts while preserving exact values
(IR-compare mode verifies semantics against the original sources).

Usage:
  py build_360_mirror.py --root <ctr360 root> --out <mirror dir> [--debug-print N]
"""

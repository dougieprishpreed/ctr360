# Overlay data .inc files use helper macros that expand to C99 array
# designators ([(OFFSET)] = ...). The source-text scan cannot see them (the
# '[' only exists after macro expansion), so cl16 meets raw designators it
# rejects. Expand with the preprocessor first; the normal pass then rewrites
# the now-literal designators positionally.
MACRO_DESIGNATOR_INCS = [
    ("game/233/R233.c", "game/233/D233_data.inc"),
]

def expand_macro_designators(mirror, log, clang="clang"):
    for driver_rel, inc_rel in MACRO_DESIGNATOR_INCS:
        driver_p = os.path.join(mirror, driver_rel)
        inc_p = os.path.join(mirror, inc_rel)
        if not (os.path.exists(driver_p) and os.path.exists(inc_p)):
            continue
        t = b2s(read_bytes(driver_p))
        body = b2s(read_bytes(inc_p))
        lines = t.split("\n")
        defs = []
        i = 0
        while i < len(lines):
            ln = lines[i]
            if ln.startswith("#define"):
                defs.append(ln)
                while defs[-1].rstrip().endswith("\\") and i + 1 < len(lines):
                    i += 1
                    defs.append(lines[i])
            i += 1
        if not defs:
            continue
        marker = "CTR360_EXPAND_INC"
        tu = "\n".join(defs) + "\n" + marker + "\n" + body + "\n"
        tmp = os.path.join(mirror, os.path.dirname(inc_rel), "_inc_expand_tmp.c")
        write_bytes(tmp, s2b(tu))
        try:
            r = subprocess.run([clang, "-E", "-P", "-x", "c", tmp],
                               capture_output=True, timeout=300)
            out_txt = r.stdout.decode("utf-8", "replace")
            idx = out_txt.find(marker)
            if idx < 0:
                raise RuntimeError("expand marker missing for " + inc_rel)
            expanded = out_txt[idx + len(marker):].strip()
            if "[" not in expanded:
                raise RuntimeError("expansion produced no designators: " + inc_rel)
            write_bytes(inc_p, s2b(expanded + "\n"))
            log("expanded macro designators: %s (%d -> %d chars, %d '[')"
                % (inc_rel, len(body), len(expanded), expanded.count("[")))
        finally:
            try:
                os.remove(tmp)
            except OSError:
                pass

def insert_before_marker(text, marker_rx, block):
    m = re.search(marker_rx, text)
    if not m:
        raise RuntimeError("insert marker not found: " + marker_rx)
    return text[:m.start()] + block + text[m.start():]

def apply_site_patches(mirror, log):
    for path, rx, repl, note in SITE_PATCHES:
        p = os.path.join(mirror, path)
        t = b2s(read_bytes(p))
        t2, n = re.subn(rx, repl, t, count=1)
        if n != 1:
            raise RuntimeError("site patch failed in %s: %s" % (path, note))
        write_bytes(p, s2b(t2))
        log("patched %s: %s -> %s" % (path, note, repl))


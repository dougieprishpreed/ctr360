def annotate(node, state):
    """Tag every location dict with the file it belongs to. clang's JSON elides
    repeated file names; walking in document order reproduces its state. Only
    real locations (offset-bearing dicts) may update the state - `includedFrom`
    and similar metadata also carry a "file" key but must not clobber it."""
    if isinstance(node, dict):
        f = node.get("file")
        if isinstance(f, str) and "offset" in node:
            state["cur"] = f
        if "offset" in node:
            node["_file"] = state["cur"]
        for v in node.values():
            annotate(v, state)
    elif isinstance(node, list):
        for v in node:
            annotate(v, state)

def dump_unit(unit_rel, mirror, clang, log):
    cmd = [clang, "-fsyntax-only", "-m32", "-DCTR_NATIVE", "-I", "include",
           "-I", "platform/xbox360/sdl_shim",
           "-Wno-incompatible-function-pointer-types", "-Wno-incompatible-pointer-types",
           "-Wno-int-conversion", "-Wno-excess-initializers", "-Wno-pointer-sign",
           "-Wno-error", "-ferror-limit=50",
           "-x", "c",
           "-Xclang", "-ast-dump=json", unit_rel.replace(os.sep, "/")]
    r = subprocess.run(cmd, cwd=mirror, capture_output=True)
    d = None
    try:
        cand = json.loads(r.stdout)
        if isinstance(cand, dict) and "inner" in cand:
            d = cand
    except (ValueError, json.JSONDecodeError):
        d = None
    if d is None:
        raise RuntimeError("clang dump failed for %s (rc=%d, %d bytes stdout):\n%s"
                           % (unit_rel, r.returncode, len(r.stdout),
                              r.stderr.decode("utf-8", "replace")[:2000]))
    if r.returncode != 0:
        raise RuntimeError("clang rejected %s (rc=%d); refusing to transform a partial AST:\n%s"
                           % (unit_rel, r.returncode,
                              r.stderr.decode("utf-8", "replace")[:4000]))
    annotate(d, {"cur": rel_norm(unit_rel)})
    return d

class Ctx:
    def __init__(self, root):
        self.root = root
        self.cache = {}
        self.mb = {}

    def bytes_for(self, f):
        if f is None:
            return None
        if f not in self.cache:
            try:
                self.cache[f] = read_bytes(os.path.join(self.root, f))
            except OSError:
                self.cache[f] = None
        return self.cache[f]

    def forget(self, f):
        """Drop the cached bytes for a file after it has been rewritten, so
        later extraction (e.g. the hoist pass) never slices stale text."""
        if f is not None:
            self.cache.pop(f, None)

    def macro_blocks(self, f):
        """[(start, end, name, params_tuple_or_None, has_hash)] per #define block."""
        if f not in self.mb:
            blocks = []
            buf = self.bytes_for(f)
            if buf:
                text = b2s(buf)
                lines = text.splitlines(keepends=True)
                off = 0
                i = 0
                while i < len(lines):
                    if re.match(r"\s*#\s*define\b", lines[i]):
                        j = i
                        while lines[j].rstrip("\r\n").endswith("\\") and j + 1 < len(lines):
                            j += 1
                        body = "".join(lines[i:j + 1])
                        span = len(body)
                        m = re.match(r"\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)", lines[i])
                        name = m.group(1) if m else None
                        params = tuple(p.strip() for p in m.group(2).split(",") if p.strip()) if m else None
                        rest = re.sub(r"^\s*#\s*define\s+[A-Za-z_][A-Za-z0-9_]*(\s*\([^)]*\))?", "", body)
                        has_hash = ("##" in rest) or bool(re.search(r"#\s*[A-Za-z_\"]", rest))
                        blocks.append((off, off + span, name, params, has_hash))
                        off += span
                        i = j + 1
                    else:
                        off += len(lines[i])
                        i += 1
            self.mb[f] = blocks
        return self.mb[f]

    def macro_params_at(self, f, off):
        """Params of the function-like macro whose body contains byte `off`,
        else None."""
        if f is None:
            return None
        for s, e, name, params, has_hash in self.macro_blocks(f):
            if s <= off < e:
                return params
        return None

    def macro_call_args(self, f, off):
        """Parse NAME(a, b, ...) at use-site offset `off`; returns
        (name, [arg text, ...]) or None."""
        buf = self.bytes_for(f)
        if buf is None:
            return None
        span = balanced_call_span(buf, off)
        if not span:
            return None
        call = b2s(buf[span[0]: span[1]])
        mm = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", call, re.S)
        if not mm:
            return None
        args, depth, cur, instr = [], 0, [], None
        for ch in mm.group(2):
            if instr:
                cur.append(ch)
                if ch == instr:
                    instr = None
                elif ch == "\\":
                    cur.append("")
                continue
            if ch in "\"'":
                instr = ch
                cur.append(ch)
            elif ch in "([{":
                depth += 1
                cur.append(ch)
            elif ch in ")]}":
                depth -= 1
                cur.append(ch)
            elif ch == "," and depth == 0:
                args.append("".join(cur).strip())
                cur = []
            else:
                cur.append(ch)
        tail = "".join(cur).strip()
        if tail or args:
            args.append(tail)
        return mm.group(1), args

    def line_of(self, f, off):
        buf = self.bytes_for(f)
        if buf is None or off is None:
            return "?"
        return buf.count(b"\n", 0, off) + 1

def build_type_db(dump):
    typedefs, records = {}, {}

    def rec_key(n):
        """Records are indexed by tag name, or by location for anonymous ones
        (clang spells those as '(unnamed at file:line:col)' in qualType)."""
        nm = n.get("name")
        if nm:
            return nm
        loc = n.get("loc", {})
        if "line" in loc and "col" in loc:
            f = loc_norm(loc.get("_file")) if loc.get("_file") else None
            return ("loc", f, loc.get("line"), loc.get("col"))
        return None

    def walk(n):
        k = n.get("kind")
        if k == "TypedefDecl" and not n.get("isImplicit"):
            nm, t = n.get("name"), n.get("type", {}).get("qualType")
            if nm and t:
                typedefs[nm] = t
            # Alias an anonymous record under its typedef name: clang spells
            # such a typedef's own qualType as the typedef name itself, so
            # record_of() can never reach the location-keyed record otherwise.
            if nm:
                rec = n
                for _ in range(4):
                    kids = [x for x in rec.get("inner", [])
                            if x.get("kind") not in ("FullComment",)]
                    if len(kids) != 1:
                        rec = None
                        break
                    rec = kids[0]
                    if rec.get("kind") == "RecordDecl":
                        break
                if rec is not None and rec.get("kind") == "RecordDecl":
                    fields = [(c.get("name"), c.get("type", {}).get("qualType", ""))
                              for c in rec.get("inner", []) if c.get("kind") == "FieldDecl"]
                    if fields:
                        records[nm] = {"kind": rec.get("tagUsed") or "struct",
                                       "fields": fields}
        if k == "RecordDecl" and n.get("tagUsed") in ("struct", "union"):
            key = rec_key(n)
            fields = [(c.get("name"), c.get("type", {}).get("qualType", ""))
                      for c in n.get("inner", []) if c.get("kind") == "FieldDecl"]
            if key is not None and fields:
                records[key] = {"kind": n["tagUsed"], "fields": fields}
        for c in n.get("inner", []):
            walk(c)

    walk(dump)
    return typedefs, records

def record_of(qt, typedefs, records, depth=0):
    if depth > 8:
        return None
    qt = qt.strip()
    while qt.startswith(("const ", "volatile ")):
        qt = qt.split(" ", 1)[1]
    if qt.startswith(("struct ", "union ")):
        rest = qt.split(" ", 1)[1]
        rec = records.get(rest)
        if rec:
            return rec
        m = re.search(r"\((?:unnamed|anonymous)[^)]*\)", rest)
        if m:
            fm = re.match(r".*?at (.+):(\d+):(\d+)$", m.group(0)[1:-1])
            if fm:
                return records.get(("loc", loc_norm(fm.group(1)),
                                    int(fm.group(2)), int(fm.group(3))))
        return None
    if qt in typedefs:
        return record_of(typedefs[qt], typedefs, records, depth + 1)
    return None

def base_kind(qt, typedefs, records):
    qt = qt.strip()
    while qt.startswith(("const ", "volatile ")):
        qt = qt.split(" ", 1)[1]
    if qt.endswith("]"):
        return "array"
    if qt.endswith("*"):
        return "pointer"
    if qt.startswith("enum "):
        return "scalar"
    rec = record_of(qt, typedefs, records)
    if rec:
        return rec["kind"]
    if "anonymous" in qt:
        return "struct"
    return "scalar"

def same_type_spelling(a, b):
    def norm(s):
        s = re.sub(r"\(anonymous[^)]*\)", "(anon)", s.strip().lower())
        return re.sub(r"\s+", " ", s)
    return norm(a) == norm(b)

def list_span(n):
    """Plain (non-macro) span of a list node; None if macro-generated."""
    r = n.get("range", {})
    b, e = r.get("begin", {}), r.get("end", {})
    for loc in (b, e):
        if "spellingLoc" in loc or "expansionLoc" in loc:
            return None
    if "offset" not in b or "offset" not in e:
        return None
    start = b["offset"]
    end = e["offset"] + (e.get("tokLen") or 1)
    if start >= end:
        return None
    return start, end, b.get("_file")

def target_hint(sp, ctx):
    if not sp or not sp[2]:
        return "?"
    return rel_norm(sp[2])

def elements(n):
    """Semantic element list. For arrays clang dumps 'array_filler' as
    [filler-template, elem0, elem1, ...]; trailing fillers are omitted."""
    if "array_filler" in n:
        af = n["array_filler"]
        af = af if isinstance(af, list) else [af]
        return af[1:]
    return n.get("inner", [])

def is_implicit(n):
    return n.get("kind") == "ImplicitValueInitExpr"

def balanced_call_span(buf, off):
    """Span of `IDENT(...)` starting at off, parens balanced, strings skipped.
    Used to recover full source text of function-like macro invocations."""
    n = len(buf)
    i = off
    while i < n and (buf[i:i + 1].isalnum() or buf[i:i + 1] == b"_"):
        i += 1
    if i >= n or buf[i:i + 1] != b"(":
        return None
    depth = 0
    j = i
    while j < n:
        c = buf[j:j + 1]
        if c == b"(":
            depth += 1
        elif c == b")":
            depth -= 1
            if depth == 0:
                return off, j + 1
        elif c in (b'"', b"'"):
            q = c
            j += 1
            while j < n and buf[j:j + 1] != q:
                if buf[j:j + 1] == b"\\":
                    j += 1
                j += 1
        j += 1
    return None

def child_text(n, ctx, log):
    """Source text for a non-list initializer child.

    Spelling first (the literal token). If the spelling text lives in a
    macro body and references that macro's parameters, it is not
    self-contained at the use site - fall back to the use-site invocation
    text (balanced-paren scan from the expansion location)."""
    r = n.get("range", {})
    b, e = r.get("begin", {}), r.get("end", {})
    sp_loc = b.get("spellingLoc")
    exp_loc = b.get("expansionLoc")

    def slice_loc(loc_begin, loc_end):
        if not loc_begin or not loc_end or "offset" not in loc_begin or "offset" not in loc_end:
            return None
        f = rel_norm(loc_begin.get("_file")) if loc_begin.get("_file") else None
        buf = ctx.bytes_for(f)
        if buf is None:
            return None
        ln = loc_end["offset"] + (loc_end.get("tokLen") or 1) - loc_begin["offset"]
        if ln <= 0 or loc_begin["offset"] + ln > len(buf):
            return None
        txt = b2s(buf[loc_begin["offset"]: loc_begin["offset"] + ln])
        return txt if txt.strip() else None

    if sp_loc and "offset" in sp_loc:
        sp_txt = slice_loc(sp_loc, e.get("spellingLoc"))
        if sp_txt is not None:
            sp_file = rel_norm(sp_loc.get("_file")) if sp_loc.get("_file") else None
            params = ctx.macro_params_at(sp_file, sp_loc["offset"])
            if not params:
                return sp_txt
            toks = set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", sp_txt))
            used = toks & set(params)
            if not used:
                return sp_txt
            # macro-body text referencing its parameters: substitute the
            # argument text from the use site (constant-folded at the call)
            if exp_loc and "offset" in exp_loc:
                ef = rel_norm(exp_loc.get("_file")) if exp_loc.get("_file") else None
                call = ctx.macro_call_args(ef, exp_loc["offset"])
                if call:
                    name, args = call
                    block = None
                    for s, en, nm, prm, hh in ctx.macro_blocks(sp_file):
                        if s <= sp_loc["offset"] < en:
                            block = (nm, prm, hh)
                            break
                    if block and block[0] and not block[2] and block[1] and name == block[0] \
                            and len(block[1]) == len(args):
                        sub = sp_txt
                        for pn, av in zip(block[1], args):
                            if pn in used:
                                sub = re.sub(r"\b%s\b" % re.escape(pn), "(" + av + ")", sub)
                        if set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", sub)) & set(block[1]) == set():
                            return sub
            # else fall through to the invocation-text fallback below
    if exp_loc and "offset" in exp_loc and "offset" in exp_loc:
        f = rel_norm(exp_loc.get("_file")) if exp_loc.get("_file") else None
        buf = ctx.bytes_for(f)
        if buf is not None:
            if not exp_loc.get("isMacroArgExpansion"):
                span = balanced_call_span(buf, exp_loc["offset"])
                if span and span[1] <= len(buf):
                    return b2s(buf[span[0]:span[1]])
            txt = slice_loc(exp_loc, e.get("expansionLoc"))
            if txt is not None:
                return txt
    return slice_loc(b, e)

def macro_list_text(n, ctx, log):
    """Use-site text of a list produced by a macro expansion. Such lists must
    NOT be regenerated from their children (the macro body is already patched
    to positional form) - emit the invocation as written instead."""
    r = n.get("range", {})
    b, e = r.get("begin", {}), r.get("end", {})
    exp = b.get("expansionLoc")
    if exp and "offset" in exp:
        f = rel_norm(exp.get("_file")) if exp.get("_file") else None
        buf = ctx.bytes_for(f)
        if buf is not None:
            if not exp.get("isMacroArgExpansion"):
                span = balanced_call_span(buf, exp["offset"])
                if span and span[1] <= len(buf):
                    return b2s(buf[span[0]:span[1]])
            se = e.get("expansionLoc")
            if se and "offset" in se:
                ln = se["offset"] + (se.get("tokLen") or 1) - exp["offset"]
                if ln > 0 and exp["offset"] + ln <= len(buf):
                    txt = b2s(buf[exp["offset"]: exp["offset"] + ln])
                    if txt.strip():
                        return txt
    return None

def flatten_fixups(unode, path_base, fx, ctx, typedefs, records, log):
    """Emit runtime assignment statements for a union list whose designated
    member is not the union's first member (not expressible positionally in
    C89). Walks the semantic tree; leaf values come from the original source.
    Returns the number of statements, or None on failure."""
    explicits = [k for k in elements(unode) if not is_implicit(k)]
    if not explicits:
        return None
    stmts = []

    def walk(node, p, depth):
        if depth > 24:
            return False
        t = node.get("type", {}).get("qualType", "")
        rec = record_of(t, typedefs, records)
        kids = elements(node)
        explicit = [k for k in kids if not is_implicit(k)]
        if not explicit:
            return True
        if rec and rec["kind"] == "union":
            sp = list_span(node)
            mname = None
            if sp:
                buf = ctx.bytes_for(rel_norm(sp[2]) if sp[2] else None)
                if buf:
                    mm = re.match(r"\s*\{\s*\.\s*([A-Za-z_][A-Za-z0-9_]*)",
                                  b2s(buf[sp[0]: sp[1]]))
                    if mm:
                        mname = mm.group(1)
            if mname is None:
                return False
            return walk(explicit[0], p + ["." + mname], depth + 1)
        if t.strip().endswith("]"):     # array
            for i, k in enumerate(kids):
                if is_implicit(k):
                    continue
                if not walk(k, p + ["[%d]" % i], depth + 1):
                    return False
            return True
        if rec and rec["kind"] == "struct":
            for i, k in enumerate(kids):
                if is_implicit(k):
                    continue
                if i >= len(rec["fields"]):
                    return False
                if not walk(k, p + ["." + rec["fields"][i][0]], depth + 1):
                    return False
            return True
        if node.get("kind") == "InitListExpr":
            return False
        txt = child_text(node, ctx, log)
        if txt is None:
            return False
        stmts.append("%s = %s;" % ("".join(p), txt))
        return True

    if not walk(explicits[0], list(path_base), 0):
        return None
    for s in stmts:
        fx["entries"].append({"file": fx["file"], "stmt": s})
    return len(stmts)

def gen_list(n, ctx, typedefs, records, log, unions, fx=None, depth=0):
    if depth > 24:
        return None
    t = n.get("type", {}).get("qualType", "")
    kids = elements(n)
    rec = record_of(t, typedefs, records)
    if rec and rec["kind"] == "union":
        unions.append((t, n.get("range", {}).get("begin", {}).get("offset")))
        explicits = [k for k in kids if not is_implicit(k)]
        if not explicits:
            return "{0}"
        member0 = rec["fields"][0][0] if rec["fields"] else None
        field_names = set(f[0] for f in rec["fields"])
        sp = list_span(n)
        member = None
        if sp:
            f = rel_norm(sp[2]) if sp[2] else None
            buf = ctx.bytes_for(f)
            if buf:
                head = b2s(buf[sp[0]: sp[1]])
                m = re.match(r"\s*\{\s*\.\s*([A-Za-z_][A-Za-z0-9_]*)", head)
                # accept only if it names a member of THIS union: for two-level
                # paths (.U.member = {...}) the union list's span text begins
                # with the CHILD struct's first field, not a union member
                if m and m.group(1) in field_names:
                    member = m.group(1)
        if member is None:
            # nested designator form (.U = {.member = {...}})
            for k in kids:
                if k.get("kind") in ("DesignatedInitExpr", "DesignatedInitUpdateExpr"):
                    for dd in (k.get("designators") or []):
                        fld = dd.get("field") or {}
                        if fld.get("name") in field_names:
                            member = fld["name"]
        if member is None:
            # two-level form (.U.member = {...}): union list is synthetic with
            # the member's value list as its only explicit child - resolve the
            # member by matching the child's type against the union's fields
            expl = [k for k in kids if not is_implicit(k)]
            if len(expl) == 1 and expl[0].get("kind") == "InitListExpr":
                ct = (expl[0].get("type") or {}).get("qualType", "")
                crec = record_of(ct, typedefs, records)
                for fname, ftype in rec["fields"]:
                    frec = record_of(ftype, typedefs, records)
                    if crec is not None and frec is not None and crec is frec:
                        member = fname
                        break
                    if crec is None and ct.strip() == ftype.strip():
                        member = fname
                        break
        if member is None and sp is None:
            # macro-generated union list: the patched macro bodies initialize
            # the first member positionally, so accept it as the first member
            if member0:
                log("  union %s: macro-generated list -> accepting first member '%s'" % (t, member0))
                member = member0
            else:
                log("  union %s: span unreadable (macro-expanded?) -> skipping (manual review)" % t)
                return None
        if member is not None and member != member0:
            if fx is not None and fx.get("enabled"):
                nst = flatten_fixups(n, list(fx["path"]) + ["." + member], fx, ctx,
                                     typedefs, records, log)
                if nst:
                    log("  union %s: member '%s' salvaged via runtime fixups (%d stmt, %s:%s)"
                        % (t, member, nst, target_hint(sp, ctx),
                           ctx.line_of(rel_norm(sp[2]) if sp and sp[2] else None, sp[0])))
                    return "{0}"
            log("  union %s: designated member '%s' != first member '%s' (%s:%s) -> skipping"
                % (t, member, member0, target_hint(sp, ctx),
                   ctx.line_of(rel_norm(sp[2]) if sp and sp[2] else None, sp[0] if sp else None)))
            return None
        if len(explicits) != 1:
            log("  union %s: %d explicit children -> skipping" % (t, len(explicits)))
            return None
        k0 = explicits[0]
        child_fx = None
        if fx is not None:
            child_fx = dict(fx)
            child_fx["path"] = list(fx["path"]) + ["." + (member if member else (member0 or ""))]
        if k0.get("kind") == "InitListExpr":
            sub = gen_list(k0, ctx, typedefs, records, log, unions, child_fx, depth + 1)
            return None if sub is None else "{ " + sub + " }"
        txt = child_text(k0, ctx, log)
        return None if txt is None else "{ " + txt + " }"

    last_explicit = -1
    for i, k in enumerate(kids):
        if not is_implicit(k):
            last_explicit = i
    if last_explicit < 0:
        return None
    is_array = t.strip().endswith("]")
    parts = []
    for i in range(last_explicit + 1):
        k = kids[i]
        if is_implicit(k):
            parts.append("{0}")
            continue
        child_fx = None
        if fx is not None:
            seg = None
            if is_array:
                seg = "[%d]" % i
            elif rec and i < len(rec["fields"]):
                seg = "." + rec["fields"][i][0]
            if seg is not None:
                child_fx = dict(fx)
                child_fx["path"] = list(fx["path"]) + [seg]
        if k.get("kind") == "InitListExpr":
            if list_span(k) is None:
                # Macro-generated list: prefer regenerating from the semantic
                # children - macro definitions may not survive the rewrite
                # when they live inside a transformed region. Fall back to the
                # use-site invocation text when children are unrecoverable.
                sub = gen_list(k, ctx, typedefs, records, log, unions, child_fx, depth + 1)
                if sub is None:
                    txt = macro_list_text(k, ctx, log)
                    if txt is None:
                        log("  child list with macro span has no recoverable text -> failing list")
                        return None
                    bl = k.get("range", {}).get("begin", {}).get("expansionLoc") or {}
                    bf = rel_norm(bl.get("_file")) if bl.get("_file") else None
                    log("  NOTE macro-list fallback at %s:%s -> %s"
                        % (bf or "?", ctx.line_of(bf, bl.get("offset")),
                           txt[:70].replace("\n", " ")))
                    parts.append(txt)
                    continue
                parts.append(sub)
                continue
            sub = gen_list(k, ctx, typedefs, records, log, unions, child_fx, depth + 1)
            if sub is None:
                return None
            parts.append(sub)
            continue
        txt = child_text(k, ctx, log)
        if txt is None:
            return None
        parts.append(txt)
    return "{ " + ", ".join(parts) + " }"

def collect_edits_for_file(dump, target_rel, ctx, log, debug_print, macro_only=False):
    """Two passes over one unit's dump, for one file:
       - top-level plain lists -> full designator transform (targets only)
       - every macro-generated list whose expansion lies in this file and is
         not inside a transformed parent -> replace the invocation span with
         the dissolved braces (macro calls are not legal in initializer lists
         under the XDK compiler, and defs may not survive the rewrite).
    macro_only files (no designators) get only the second pass, so their plain
    lists (and comments inside them) stay byte-identical."""
    typedefs, records = build_type_db(dump)
    edits, skipped, unions, fixups = [], [], [], []
    macro_cands = []
    dbg = {"n": 0}
    lit_n = [0]

    def plain_span(n):
        r = n.get("range", {})
        b, e = r.get("begin", {}), r.get("end", {})
        if "offset" not in b or "offset" not in e:
            return None
        if "spellingLoc" in b or "expansionLoc" in b:
            return None
        return (b["offset"], e["offset"] + (e.get("tokLen") or 1))

    def plain_text(n):
        sp = plain_span(n)
        if not sp:
            return None
        buf = ctx.bytes_for(target_rel)
        if buf is None or sp[1] > len(buf):
            return None
        return b2s(buf[sp[0]: sp[1]])

    def stmt_end_off(off):
        buf = ctx.bytes_for(target_rel)
        if buf is None:
            return off
        i = off
        while i < len(buf) and buf[i:i + 1] in (b" ", b"\t", b"\r", b"\n"):
            i += 1
        return i + 1 if buf[i:i + 1] == b";" else off

    def handle_compound_literal(lit, whole_span, lhs_txt, in_stmt):
        """Rewrite an expression-context compound literal (C99) into C89:
        - assignment statement: '{ T tmp = {..}; lhs = tmp; }'
        - auto declaration init: plain brace list."""
        lb = lit.get("range", {}).get("begin", {})
        lf = loc_norm(lb.get("_file")) if lb.get("_file") else None
        if lf != target_rel or whole_span is None:
            return False
        lit_txt = plain_text(lit)
        if not lit_txt or "{" not in lit_txt:
            return False
        braces = lit_txt[lit_txt.index("{"):]
        # the literal braces are copied from the source text; strip `.field =`
        # designators the same way macro bodies are stripped (the known
        # expression-context literal sites use in-order scalar designators)
        if "[" in braces:
            log("  compound literal keeps array designators (%s): manual review" % target_rel)
        braces = re.sub(r"([{,]\s*)\.\s*[A-Za-z_][A-Za-z0-9_]*\s*=\s*", r"\1", braces)
        if re.search(r"[{,]\s*\.\s*[A-Za-z_]", braces):
            log("  compound literal still has designators (%s): manual review" % target_rel)
            return False
        type_sp = lit.get("type", {}).get("qualType", "")
        if not type_sp:
            return False
        if in_stmt == "return":
            end = stmt_end_off(whole_span[1])
            tmp = "ctr360_lit_%d" % lit_n[0]
            lit_n[0] += 1
            edits.append((whole_span[0], end,
                          "{ %s %s = %s; return %s; }" % (type_sp, tmp, braces, tmp)))
            log("  compound literal -> return block (%s, %s)" % (target_rel, type_sp))
        elif in_stmt:
            if lhs_txt is None:
                return False
            end = stmt_end_off(whole_span[1])
            tmp = "ctr360_lit_%d" % lit_n[0]
            lit_n[0] += 1
            edits.append((whole_span[0], end,
                          "{ %s %s = %s; %s = %s; }" % (type_sp, tmp, braces, lhs_txt, tmp)))
            log("  compound literal -> statement block (%s, %s)" % (target_rel, type_sp))
        else:
            edits.append((whole_span[0], whole_span[1], braces))
            log("  compound literal -> brace list (%s, %s)" % (target_rel, type_sp))
        return True

    def unwrap_cast(node):
        # The semantic AST wraps compound literals in ImplicitCastExpr
        # (`pos = (SVec3){...}` -> BinaryOperator[=, pos, ImplicitCastExpr[
        # CompoundLiteralExpr]]), so always unwrap before checking the kind.
        while (isinstance(node, dict)
               and node.get("kind") in ("ImplicitCastExpr", "ParenExpr")
               and len(node.get("inner", [])) == 1):
            node = node["inner"][0]
        return node

    def visit(n, inside, state, parent_kind=None):
        k = n.get("kind")
        if k == "FunctionDecl":
            st2 = dict(state)
            st2["in_func"] = True
            for c in n.get("inner", []):
                visit(c, inside, st2, "FunctionDecl")
            return
        if k == "VarDecl":
            st2 = dict(state)
            st2["var"] = n.get("name")
            st2["is_const"] = "const" in (n.get("type", {}).get("qualType") or "")
            inner = n.get("inner", [])
            if inner:
                ini = unwrap_cast(inner[0])
                if ini.get("kind") == "CompoundLiteralExpr":
                    sp = plain_span(ini)
                    if handle_compound_literal(ini, sp, None, False):
                        return
            for c in inner:
                visit(c, inside, st2, "VarDecl")
            return
        if k == "BinaryOperator" and n.get("opcode") == "=" and state.get("in_func"):
            inner = n.get("inner", [])
            if len(inner) == 2:
                rhs = unwrap_cast(inner[1])
                if rhs.get("kind") == "CompoundLiteralExpr":
                    sp = plain_span(n)
                    lhs_txt = plain_text(inner[0])
                    if handle_compound_literal(rhs, sp, lhs_txt, True):
                        return
            for c in inner:
                visit(c, inside, state, "BinaryOperator")
            return
        if k == "ReturnStmt" and state.get("in_func"):
            inner = n.get("inner", [])
            if inner:
                rv = unwrap_cast(inner[0])
                if rv.get("kind") == "CompoundLiteralExpr":
                    sp = plain_span(n)
                    if handle_compound_literal(rv, sp, None, "return"):
                        return
            for c in inner:
                visit(c, inside, state, "ReturnStmt")
            return
        if k == "InitListExpr":
            b = n.get("range", {}).get("begin", {})
            f = loc_norm(b.get("_file")) if b.get("_file") else None
            if f is None:
                el = b.get("expansionLoc") or {}
                f = loc_norm(el.get("_file")) if el.get("_file") else None
            if f == target_rel:
                sp = list_span(n)
                if sp is not None and not inside and not macro_only:
                    enabled = bool(state.get("var")) and not state.get("in_func") \
                        and not state.get("is_const")
                    fx = {"enabled": enabled, "path": [state.get("var") or ""],
                          "entries": fixups, "file": target_rel}
                    txt = gen_list(n, ctx, typedefs, records, log, unions, fx)
                    if txt is None:
                        skipped.append(("unsupported list", sp[0]))
                        return
                    if dbg["n"] < debug_print:
                        dbg["n"] += 1
                        log("  [dbg] %s span %d..%d -> %s" % (target_rel, sp[0], sp[1], txt[:120].replace("\n", " ")))
                    edits.append((sp[0], sp[1], txt))
                    return
                if sp is None:
                    exp = b.get("expansionLoc") or {}
                    ef = loc_norm(exp.get("_file")) if exp.get("_file") else None
                    if ef == target_rel and "offset" in exp:
                        if parent_kind in ("InitListExpr", "VarDecl"):
                            buf = ctx.bytes_for(ef)
                            span = balanced_call_span(buf, exp["offset"]) if buf else None
                            if span:
                                macro_cands.append((span, n, dict(state)))
                                return
                            skipped.append(("macro span, unusable invocation", b.get("offset")))
                            return
                        log("  macro list left for function form at %s:%s (parent %s)"
                            % (target_rel, ctx.line_of(target_rel, exp["offset"]), parent_kind))
                        return
                for c in n.get("inner", []):
                    visit(c, True, state, "InitListExpr")
                return
            for c in n.get("inner", []):
                visit(c, True, state, "InitListExpr")
            return
        for c in n.get("inner", []):
            visit(c, inside, state, k)

    visit(dump, False, {}, None)

    for span, node, st2 in macro_cands:
        enabled = bool(st2.get("var")) and not st2.get("in_func") and not st2.get("is_const")
        fx = {"enabled": enabled, "path": [st2.get("var") or ""],
              "entries": fixups, "file": target_rel}
        txt = gen_list(node, ctx, typedefs, records, log, unions, fx)
        if txt is None:
            skipped.append(("macro list not dissolvable", span[0]))
            continue
        edits.append((span[0], span[1], txt))
        log("  macro list dissolved at %s:%s -> %s"
            % (target_rel, ctx.line_of(target_rel, span[0]), txt[:70].replace("\n", " ")))
    return edits, skipped, unions, fixups

def collect_hoists_for_file(dump, target_rel, ctx, log):
    """C89 declaration hoisting: the XDK compiler requires all declarations at
    the top of their block.
      - late DeclStmts (after statements): scalars hoist as 'T name;' with the
        initializer turned into an assignment at the original spot; uninit or
        constant-initialized aggregates move whole.
      - 'for (int i = ...)': 'int i;' hoisted, init becomes 'i = ...'.
    Returns edits [(start, end, text)] and a list of manual-review notes."""
    edits, notes = [], []
    aggr_n = [0]
    buf = ctx.bytes_for(target_rel)
    if buf is None:
        return edits, notes

    def span_of(n):
        r = n.get("range", {})
        b, e = r.get("begin", {}), r.get("end", {})
        if "offset" not in b or "offset" not in e:
            return None
        if "spellingLoc" in b or "expansionLoc" in e:
            return None
        bf = loc_norm(b.get("_file")) if b.get("_file") else None
        ef = loc_norm(e.get("_file")) if e.get("_file") else None
        if bf != target_rel or (ef is not None and ef != target_rel):
            return None
        return (b["offset"], e["offset"] + (e.get("tokLen") or 1))

    def text_of(sp):
        if not sp or sp[1] > len(buf):
            return None
        return b2s(buf[sp[0]: sp[1]])

    def scan_expr_end(off, list_leaf=False):
        """From a plain-text offset, scan to the end of the expression: the
        terminator (';' at depth 0, or also ','/'}' for a list leaf) exclusive.
        Handles strings and comments."""
        i, depth, in_str = off, 0, None
        n = len(buf)
        while i < n:
            ch = buf[i:i + 1]
            if in_str:
                if ch == b"\\":
                    i += 2
                    continue
                if ch == in_str:
                    in_str = None
                i += 1
                continue
            if ch == b"/" and buf[i + 1:i + 2] == b"/":
                j = buf.find(b"\n", i)
                i = n if j < 0 else j + 1
                continue
            if ch == b"/" and buf[i + 1:i + 2] == b"*":
                j = buf.find(b"*/", i + 2)
                i = n if j < 0 else j + 2
                continue
            if ch in (b'"', b"'"):
                in_str = ch
            elif ch in (b"(", b"[", b"{"):
                depth += 1
            elif ch in (b")", b"]", b"}"):
                depth -= 1
                if list_leaf and depth < 0:
                    return i
            elif ch == b"," and list_leaf and depth <= 0:
                return i
            elif ch == b";" and depth <= 0:
                return i
            i += 1
        return None

    def expr_span(n, list_leaf=False):
        """Span for an expression node, tolerating macro expansions at either
        end: fall back to scanning from the plain (or expansion) begin offset."""
        sp = span_of(n)
        if sp is not None:
            return sp
        b = n.get("range", {}).get("begin", {})
        boff = b.get("offset")
        if boff is None:
            el = b.get("expansionLoc") or {}
            boff = el.get("offset")
        if boff is None:
            return None
        e = scan_expr_end(boff, list_leaf=list_leaf)
        if e is None:
            return None
        return (boff, e)

    def stmt_span(n):
        sp = span_of(n)
        if sp is not None:
            return sp
        b = n.get("range", {}).get("begin", {})
        boff = b.get("offset")
        if boff is None:
            el = b.get("expansionLoc") or {}
            boff = el.get("offset")
        if boff is None:
            return None
        e = scan_expr_end(boff)
        if e is None:
            return None
        return (boff, e + 1)

    def is_const_expr(n, depth=0):
        if depth > 24:
            return False
        k = n.get("kind")
        if k in ("IntegerLiteral", "FloatingLiteral", "CharacterLiteral",
                 "StringLiteral", "ImplicitValueInitExpr", "GNUNullExpr",
                 "CXXBoolLiteralExpr", "PredefinedExpr"):
            return True
        if k == "DeclRefExpr":
            rd = n.get("referencedDecl") or {}
            return rd.get("kind") == "EnumConstantDecl"
        if k in ("CallExpr", "ArraySubscriptExpr", "MemberExpr", "BinaryOperator"):
            return False
        if k in ("UnaryOperator", "CastExpr", "ImplicitCastExpr", "CStyleCastExpr",
                 "ParenExpr", "InitListExpr", "UnaryExprOrTypeTraitExpr",
                 "ConditionalOperator", "VAArgExpr"):
            kids = n.get("inner", [])
            if k == "UnaryExprOrTypeTraitExpr":
                return True
            if k in ("CastExpr", "ImplicitCastExpr", "CStyleCastExpr", "ParenExpr"):
                for c in kids:
                    if c.get("kind") == "TypeExpr" or "Type" in c.get("kind", ""):
                        continue
                    if not is_const_expr(c, depth + 1):
                        return False
                return True
            if k == "ConditionalOperator":
                return all(is_const_expr(c, depth + 1) for c in kids)
            for c in kids:
                if c.get("kind", "").endswith("Type"):
                    continue
                if not is_const_expr(c, depth + 1):
                    return False
            return True
        return False

    def for_decl_walk(n, found):
        """collect ForStmts with a DeclStmt init within this block (not crossing
        nested CompoundStmts)."""
        if isinstance(n, dict):
            if n.get("kind") == "ForStmt":
                kids = n.get("inner", [])
                if kids and kids[0].get("kind") == "DeclStmt":
                    found.append((n, kids[0]))
                for c in kids:
                    if c.get("kind") != "DeclStmt":
                        for_decl_walk(c, found)
                return
            if n.get("kind") == "CompoundStmt":
                return
            for c in n.get("inner", []):
                for_decl_walk(c, found)
        elif isinstance(n, list):
            for c in n:
                for_decl_walk(c, found)

    typedefs, records = build_type_db(dump)

    def flatten_aggr(node, path, stmts, depth=0):
        """Emit per-leaf assignment statements for a non-constant aggregate
        initializer, so a hoisted bare declaration reproduces it exactly.
        Returns True when the whole initializer was handled."""
        if node is None or depth > 8:
            return False
        k = node.get("kind")
        if k == "InitListExpr":
            tq = node.get("type", {}).get("qualType", "") or ""
            kids = [c for c in node.get("inner", [])
                    if not c.get("kind", "").endswith("Type")]
            if base_kind(tq, typedefs, records) == "array":
                idx = 0
                for c in kids:
                    ck = c.get("kind")
                    if ck == "array_filler":
                        continue
                    if ck == "ArrayInitLoopExpr":
                        return False
                    if not flatten_aggr(c, "%s[%d]" % (path, idx), stmts, depth + 1):
                        return False
                    idx += 1
                return True
            rec = record_of(tq, typedefs, records)
            if rec is None:
                return False
            fields = [f for f in rec["fields"] if f[0]]
            if len(kids) > len(fields):
                return False
            for i, c in enumerate(kids):
                ck = c.get("kind")
                fname = fields[i][0] if i < len(fields) else None
                if fname is None:
                    return False
                sub = "%s.%s" % (path, fname)
                if ck == "ImplicitValueInitExpr":
                    sub_tq = c.get("type", {}).get("qualType", "") or ""
                    if base_kind(sub_tq, typedefs, records) == "scalar":
                        stmts.append("%s = 0;" % sub)
                        continue
                    return False
                if not flatten_aggr(c, sub, stmts, depth + 1):
                    return False
            return True
        sp = expr_span(node, list_leaf=True)
        txt = text_of(sp) if sp else None
        if txt is None:
            return False
        stmts.append("%s = %s;" % (path, txt))
        return True

    def process_block(block):
        kids = block.get("inner", [])
        bsp = span_of(block)
        if bsp is None:
            return
        first_nondecl = None
        decls = []
        for c in kids:
            if c.get("kind") == "DeclStmt":
                if first_nondecl is None:
                    decls.append(("lead", c))
                else:
                    decls.append(("late", c))
            elif first_nondecl is None:
                first_nondecl = c
        insert_off = None
        leads = [c for tag, c in decls if tag == "lead"]
        if leads:
            # stmt_span (not span_of): leading declarations frequently begin
            # with a macro (e.g. "RECT x;" with RECT a #define), whose begin
            # location has no plain offset - scan-based recovery handles that.
            lsp = stmt_span(leads[-1])
            insert_off = lsp[1] if lsp else (bsp[0] + 1)
        else:
            insert_off = bsp[0] + 1
        if insert_off is None:
            return
        hoisted = []      # declaration texts to insert at block top
        hoist_names = set()

        def new_name_ok(name):
            if name in hoist_names:
                return False
            hoist_names.add(name)
            return True

        # late DeclStmts
        for tag, ds in decls:
            if tag != "late":
                continue
            dsp = stmt_span(ds)
            vds = [c for c in ds.get("inner", []) if c.get("kind") == "VarDecl"]
            if dsp is None or not vds:
                if dsp is not None and not vds:
                    # non-variable declaration (local prototype, typedef, struct):
                    # move it whole to the block top, delete it at the site
                    txt = text_of(dsp)
                    if txt is not None:
                        t = txt.rstrip()
                        if not t.endswith(";"):
                            t += ";"
                        hoisted.append(t)
                        edits.append((dsp[0], dsp[1], ""))
                        continue
                notes.append("%s: late decl unhandled: %s"
                             % (target_rel, (text_of(dsp) or "?").replace("\n", " ")[:90]))
                continue
            ds_txt = text_of(dsp)
            # per-declarator plan
            plan = []   # (hoist_text_or_None, replace_text)
            multi = len(vds) > 1
            ok = True
            for vd in vds:
                name = vd.get("name") or "?"
                tq = vd.get("type", {}).get("qualType", "")
                init = None
                for c in vd.get("inner", []):
                    if c.get("kind") not in ("FullComment",):
                        init = c
                        break
                    init = None
                tsp = expr_span(vd)
                vtxt = text_of(tsp)
                if vtxt is None:
                    ok = False
                    break
                vtxt = vtxt.rstrip().rstrip(";").rstrip()
                if init is None:
                    plan.append((vtxt + ";", ""))
                    continue
                isp = expr_span(init)
                itxt = text_of(isp)
                if itxt is None:
                    ok = False
                    break
                is_array = tq.strip().endswith("]")
                is_aggr = (is_array or ("struct " in tq) or ("union " in tq)
                           or base_kind(tq, typedefs, records) in ("struct", "union", "array")
                           or init.get("kind") == "InitListExpr")
                if is_aggr:
                    if is_const_expr(init):
                        plan.append((vtxt + ";", ""))
                    else:
                        base = vtxt.split("=")[0].rstrip()
                        if "const" in base.split():
                            base = " ".join(t for t in base.split() if t != "const")
                        stmts = []
                        if flatten_aggr(init, name, stmts):
                            plan.append((base + ";", " ".join(stmts)))
                        elif base.endswith(name) and itxt is not None:
                            # universal fallback: statement block + auto temp
                            # (brace-list initializer for an automatic object is
                            # valid C89, and evaluation stays at the site)
                            aggr_n[0] += 1
                            tmp = "ctr360_aggr_%d" % aggr_n[0]
                            plan.append((base + ";",
                                         "{ %s%s = %s; %s = %s; }"
                                         % (base[:-len(name)], tmp, itxt, name, tmp)))
                        else:
                            ok = False
                            break
                else:
                    if multi:
                        # keep it simple: hoist whole (works when all inits are
                        # constant-foldable at decl time); flag otherwise
                        if not is_const_expr(init):
                            ok = False
                            break
                        plan.append((vtxt + ";", ""))
                    else:
                        base = vtxt.split("=")[0].rstrip()
                        is_const_q = base.startswith("const ")
                        if "const" in base.split():
                            base = " ".join(t for t in base.split() if t != "const")
                        plan.append((base + ";", "%s = %s;" % (name, itxt)))
            if not ok:
                notes.append("%s: late decl requires manual review: %s"
                             % (target_rel, (ds_txt or "").replace("\n", " ")[:80]))
                continue
            # hoist names & apply
            if multi:
                # clang gives each declarator a CUMULATIVE range for
                # "int a, b, c;" (a -> "int a", b -> "int a, b", ...), so the
                # last declarator's text is the whole statement: hoist that
                # once instead of one cumulative copy per declarator.
                h_last = plan[-1][0]
                names_here = [vd.get("name") or "?" for vd in vds]
                already = [n for n in names_here if n in hoist_names]
                if already and len(already) == len(names_here):
                    h_last = None   # every name already hoisted (e.g. a
                                    # for-decl earlier in this block)
                elif already:
                    notes.append("%s: multi-decl partially hoisted: %s"
                                 % (target_rel, ", ".join(already)))
                    continue
                else:
                    hoist_names.update(names_here)
                if h_last is not None:
                    hoisted.append(h_last)
                reps = []
                for (h, rep) in plan:
                    if rep is not None:
                        reps.append(rep)
                if reps and any(reps):
                    edits.append((dsp[0], dsp[1], " ".join(r for r in reps if r)))
                else:
                    edits.append((dsp[0], dsp[1], ""))
                continue
            reps = []
            for (h, rep), vd in zip(plan, vds):
                nm = vd.get("name") or "?"
                if new_name_ok(nm):
                    hoisted.append(h)
                if rep is not None:
                    reps.append(rep)
            if reps:
                edits.append((dsp[0], dsp[1], " ".join(reps)))
        # for-loop decls
        fords = []
        for c in kids:
            if c.get("kind") != "DeclStmt":
                for_decl_walk(c, fords)
        for fstmt, fds in fords:
            dsp = stmt_span(fds)
            fsp = span_of(fstmt)
            if dsp is None or fsp is None:
                continue
            vds = [c for c in fds.get("inner", []) if c.get("kind") == "VarDecl"]
            if len(vds) != 1:
                notes.append("%s: for-decl with %d vars unhandled" % (target_rel, len(vds)))
                continue
            vd = vds[0]
            name = vd.get("name") or "?"
            dtxt = text_of(dsp)
            if dtxt is None:
                continue
            init = None
            for c in vd.get("inner", []):
                init = c
                break
            isp = expr_span(init) if init is not None else None
            itxt = text_of(isp) if isp else None
            # declaration text without initializer
            decl_txt = dtxt.split("=")[0].rstrip()
            if "const" in decl_txt.split():
                decl_txt = " ".join(t for t in decl_txt.split() if t != "const")
            if new_name_ok(name):
                hoisted.append(decl_txt + ";")
            # the DeclStmt span includes the for-clause ';' - keep one
            semi = ";" if dtxt.rstrip().endswith(";") else ""
            if itxt is not None:
                edits.append((dsp[0], dsp[1], "%s = %s%s" % (name, itxt, semi)))
            else:
                edits.append((dsp[0], dsp[1], semi))
        if hoisted:
            ins = "\n\t" + "\n\t".join(hoisted)
            edits.append((insert_off, insert_off, ins))

    def visit(n, in_func):
        k = n.get("kind")
        if k == "FunctionDecl":
            for c in n.get("inner", []):
                visit(c, True)
            return
        if k == "CompoundStmt" and in_func:
            process_block(n)
        for c in n.get("inner", []):
            visit(c, in_func)

    visit(dump, False)
    # sort: descending start keeps offsets stable while applying
    edits.sort(key=lambda e: -e[0])
    return edits, notes


def apply_edits(buf, edits, log, path):
    seen = set()
    span_txt = {}
    uniq = []
    for e in edits:
        if (e[0], e[1]) in span_txt and span_txt[(e[0], e[1])] != e[2]:
            log("  WARN %s: conflicting edits for span %d..%d" % (path, e[0], e[1]))
        span_txt[(e[0], e[1])] = e[2]
        key = (e[0], e[1], e[2])
        if key in seen:
            continue
        seen.add(key)
        uniq.append(e)
    for start, end, txt in sorted(uniq, key=lambda x: -x[0]):
        if start < 0 or end > len(buf) or start > end:
            log("  WARN %s: bad span %d..%d" % (path, start, end))
            continue
        if buf[start:start + 1] != b"{" and txt.startswith("{ "):
            log("  WARN %s: span at %d does not start with '{' (%r ...)"
                % (path, start, buf[start:start + 16]))
        buf = buf[:start] + s2b(txt) + buf[end:]
    return buf


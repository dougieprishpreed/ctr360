def dump_units_batched(units_items, out, clang, log, batch=3):
    """Dump parse units in small parallel batches (clang runs as a subprocess,
    so a thread pool gives real parallelism) and yield
    (unit, file_list, dump_or_None) preserving the input order."""
    from concurrent.futures import ThreadPoolExecutor
    items = list(units_items)
    for i in range(0, len(items), batch):
        chunk = items[i:i + batch]
        for u, fl in chunk:
            log("== dump unit: %s (%d files)" % (u, len(fl)))
        with ThreadPoolExecutor(max_workers=len(chunk)) as ex:
            futs = [(ex.submit(dump_unit, u, out, clang, log), u, fl) for u, fl in chunk]
            for fut, u, fl in futs:
                try:
                    d = fut.result()
                except RuntimeError as e:
                    log("dump failed for %s: %s" % (u, str(e)[:200]))
                    raise
                yield u, fl, d

def build_hoist_units(out, log):
    """Unit -> [files] map for the hoist pass over an existing mirror."""
    all_src = []
    for top in ("game", "platform"):
        for dirpath, dirnames, filenames in os.walk(os.path.join(out, top)):
            dirnames[:] = [d for d in dirnames if d != ".git"]
            for fn in filenames:
                if fn.endswith((".c", ".inc")):
                    all_src.append(rel_norm(os.path.relpath(os.path.join(dirpath, fn), out)))
    all_src = sorted(set(all_src) - {"game/_ctr360_fixups.c"})
    hunits = {}
    hdefault = []
    for t in all_src:
        if t.startswith("game/230/"):
            hunits.setdefault("game/230.c", []).append(t)
        elif t.startswith("game/233/"):
            pass
        else:
            hdefault.append(t)
    h233 = [t for t in all_src if t.startswith("game/233/")]
    if h233:
        wrapper = os.path.join(out, "game", "_unit233.c")
        if not os.path.exists(wrapper):
            unity_txt2 = b2s(read_bytes(os.path.join(out, "game", "game_unity.h")))
            inc233b = re.findall(r'#include\s+"(233/[^"]+)"', unity_txt2)
            write_bytes(wrapper, s2b("#include <common.h>\n"
                                     + "".join('#include "%s"\n' % p for p in inc233b)))
        hunits["game/_unit233.c"] = h233
    for t in hdefault:
        hunits.setdefault(t, []).append(t)
    return hunits

def hoist_unit_worker(payload):
    """Process-pool worker: dump one parse unit and collect hoist edits for
    every file of the unit. Runs in a child process (no GIL contention);
    returns (unit, {file: (edits, notes)} or None, error_text_or_None)."""
    unit, file_list, out, clang = payload
    silent = lambda s: None
    try:
        d = dump_unit(unit, out, clang, silent)
    except RuntimeError as e:
        return unit, None, str(e)[:4000]
    ctx = Ctx(out)
    results = {}
    for target in file_list:
        try:
            he, hn = collect_hoists_for_file(d, rel_norm(target), ctx, silent)
        except Exception as e:
            return unit, None, "collect error in %s: %s" % (target, str(e)[:200])
        results[rel_norm(target)] = (he, hn)
    return unit, results, None

def run_hoist_pass(out, hunits, ctx, clang, log):
    """Hoist pass: function-less units skipped, unit work done in a process
    pool, edits applied sequentially in the parent."""
    from concurrent.futures import ProcessPoolExecutor

    def any_functions(rels):
        for r_ in rels:
            try:
                t_ = read_bytes(os.path.join(out, r_))
            except OSError:
                continue
            if re.search(rb"\)\s*\n?\s*\{", t_):
                return True
        return False

    items = []
    # game_unity.h excludes these PSX card/file API implementations under
    # CTR_NATIVE; native_memcard_adapter.c supplies their native replacement.
    retail_only = {
        "game/memcard/memcard_retailcard.c",
        "game/memcard/memcard_retailevents.c",
        "game/memcard/memcard_retailtransfer.c",
    }
    for unit, file_list in sorted(hunits.items()):
        # XDK sources are already written for MSVC C89. Host clang has no
        # Xbox SDK headers and cannot produce a valid AST for these units.
        if unit.startswith("platform/xbox360/"):
            log("  hoist: skip %s (XDK source compiled by MSBuild)" % unit)
            continue
        if unit in retail_only:
            log("  hoist: skip %s (retail-only source excluded by native unity)" % unit)
            continue
        if not any_functions(file_list):
            log("  hoist: skip %s (no function bodies)" % unit)
            continue
        items.append((unit, file_list))
    log("  hoist: %d unit(s) to process" % len(items))
    hoist_total = 0
    manual = []
    done = 0
    payloads = [(u, fl, out, clang) for u, fl in items]
    with ProcessPoolExecutor(max_workers=1) as ex:
        for unit, results, err in ex.map(hoist_unit_worker, payloads):
            done += 1
            if done % 25 == 0:
                log("  hoist progress: %d/%d units" % (done, len(items)))
            if err:
                log("hoist unit failed: %s: %s" % (unit, err))
                raise RuntimeError("hoist failed for %s: %s" % (unit, err))
            for target, (he, hn) in results.items():
                if he:
                    p = os.path.join(out, target)
                    buf = read_bytes(p)
                    buf = apply_edits(buf, he, log, target)
                    write_bytes(p, buf)
                    ctx.forget(rel_norm(target))
                    hoist_total += len(he)
                for n_ in hn:
                    manual.append(n_)
    return hoist_total, manual

def run_verify(out, unit_list, clang, log):
    """Parallel clang re-parse of every parse unit against the mirror."""
    from concurrent.futures import ThreadPoolExecutor

    def check(unit):
        if not os.path.exists(os.path.join(out, unit)):
            return unit, []
        cmd = [clang, "-fsyntax-only", "-m32", "-DCTR_NATIVE", "-I", "include",
               "-Wno-incompatible-function-pointer-types", "-Wno-incompatible-pointer-types",
               "-Wno-int-conversion", "-Wno-excess-initializers", "-Wno-pointer-sign",
               "-Wno-error", "-ferror-limit=50", unit]
        r = subprocess.run(cmd, cwd=out, capture_output=True)
        errs = [l for l in r.stderr.decode("utf-8", "replace").splitlines() if ": error:" in l]
        return unit, errs

    bad = 0
    with ThreadPoolExecutor(max_workers=1) as ex:
        for unit, errs in ex.map(check, unit_list):
            if errs:
                bad += 1
                log("UNIT FAIL: %s\n  %s" % (unit, "\n  ".join(errs[:6])))
    return bad

def resume_hoist_only(out, args, log):
    """--resume: hoist + leftovers + verify against an existing mirror."""
    if not os.path.isdir(os.path.join(out, "game")):
        log("RESUME: no mirror at %s" % out)
        return 2
    log("RESUME: using existing mirror at %s" % out)
    ctx = Ctx(out)
    hunits = build_hoist_units(out, log)
    if args.hoist_only:
        keep = set(rel_norm(p) for p in args.hoist_only.split(","))
        hunits = {u: [t for t in fl if t in keep] for u, fl in hunits.items()}
        hunits = {u: fl for u, fl in hunits.items() if fl}
    hoist_total, manual = run_hoist_pass(out, hunits, ctx, args.clang, log)
    log("hoist pass: %d edit(s), %d manual-review note(s)" % (hoist_total, len(manual)))
    for n_ in manual[:40]:
        log("  HOIST NOTE %s" % n_)
    leftovers = scan_designator_lines(out)
    log("leftover designator lines after transform: %d file(s)" % len(leftovers))
    if args.verify_syntax:
        bad = run_verify(out, sorted(hunits), args.clang, log)
        log("unit verify: %d failure(s)" % bad)
    wrapper = os.path.join(out, "game", "_unit233.c")
    if os.path.exists(wrapper):
        os.remove(wrapper)
    log("done (resume).")
    return 0 if not leftovers else 2

# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", required=True, help="ctr360 source root (has game/ and include/)")
    ap.add_argument("--out", required=True, help="mirror output dir (recreated)")
    ap.add_argument("--clang", default="clang")
    ap.add_argument("--debug-print", type=int, default=0,
                    help="print first N generated replacements for eyeballing")
    ap.add_argument("--verify-syntax", action="store_true",
                    help="clang -fsyntax-only every modified file afterwards")
    ap.add_argument("--no-hoist", action="store_true",
                    help="skip the C89 declaration-hoist pass (debug)")
    ap.add_argument("--hoist-only", default=None,
                    help="comma-separated file list the hoist pass is limited to (debug)")
    ap.add_argument("--only", default=None, help="comma-separated file list to transform (debug)")
    ap.add_argument("--resume", action="store_true",
                    help="operate on the existing --out mirror: skip copy/patches/transform, "
                         "run only the hoist + leftovers + verify")
    args = ap.parse_args()

    lines = []
    def log(msg):
        print(msg)
        lines.append(msg)

    root = os.path.abspath(args.root)
    out = os.path.abspath(args.out)

    # single-instance guard: two concurrent runs on one mirror produce
    # duplicated inserts (non-idempotent hoist + interleaved applies).
    lockp = os.path.join(out, ".ctr360_mirror.lock")
    if os.path.isdir(out):
        if os.path.exists(lockp):
            try:
                with open(lockp, "r") as f:
                    pid = f.read().strip()
            except OSError:
                pid = "?"
            log("LOCKED: another run appears active (lock pid %s). Delete %s to override."
                % (pid, lockp))
            return 3
        try:
            with open(lockp, "w") as f:
                f.write(str(os.getpid()))
        except OSError:
            pass

    if args.resume:
        try:
            return resume_hoist_only(out, args, log)
        finally:
            try:
                os.remove(lockp)
            except OSError:
                pass

    # 1. mirror
    if os.path.isdir(out):
        shutil.rmtree(out, ignore_errors=True)
        if os.path.isdir(out):
            # Windows can keep the directory itself locked (e.g. a shell cwd);
            # clear the contents in that case and reuse the directory.
            for name in os.listdir(out):
                p = os.path.join(out, name)
                if os.path.isdir(p):
                    shutil.rmtree(p, ignore_errors=True)
                else:
                    try:
                        os.remove(p)
                    except OSError:
                        pass
    copy_tree(os.path.join(root, "game"), os.path.join(out, "game"))
    copy_tree(os.path.join(root, "include"), os.path.join(out, "include"))
    # platform/: everything except the host files the 360 backend replaces.
    # native_audio.c and native_perf.c stay: their SDL surface is satisfied by
    # platform/xbox360/sdl_shim (audio) and compiled out without CTR_INTERNAL
    # (perf), so the SPU/XA emulation runs unmodified on the console.
    PLATFORM_EXCLUDE = {"native_renderer.c", "native_input.c",
                        "native_platform.c", "native_glad.c"}
    plat_src = os.path.join(root, "platform")
    if os.path.isdir(plat_src):
        for dirpath, dirnames, filenames in os.walk(plat_src):
            for fn in filenames:
                if fn in PLATFORM_EXCLUDE:
                    continue
                s = os.path.join(dirpath, fn)
                r = os.path.relpath(s, plat_src)
                write_bytes(os.path.join(out, "platform", r), read_bytes(s))
    log("mirror created: %s (platform minus: %s)"
        % (out, ", ".join(sorted(PLATFORM_EXCLUDE))))

    # 2. patches
    apply_all_patches(out, log)

    # 2b. expand macro-generated designators (overlay data .inc files)
    expand_macro_designators(out, log, args.clang)

    # 3. targets = files that still contain designator-looking lines
    targets = scan_designator_lines(out)
    if args.only:
        keep = {rel_norm(x) for x in args.only.split(",")}
        targets = {k: v for k, v in targets.items() if k in keep}
    log("files needing list transform: %d" % len(targets))
    for k in sorted(targets):
        log("  %s  (%d designator lines)" % (k, len(targets[k])))
    if not targets:
        log("nothing to transform")
        write_mirror_manifest(root, out)
        log("manifest: %s" % os.path.join(out, MIRROR_MANIFEST))
        try:
            os.remove(lockp)
        except OSError:
            pass
        return 0

    # 4. parse units (designator targets + macro-only files + compound-literal files)
    targets_set = set(targets)
    LIST_MACROS = ("COLOR_CODE_PACKED_INIT", "MakeColorCode", "MakeColor", "MakePoint",
                   "SET_MDM", "PHYSWRAP")
    macro_pat = re.compile(r"\b(?:%s)\s*\(" % "|".join(LIST_MACROS))
    # expression-context compound literals: `(Type){...}` / `(struct X){...}`.
    # Type names are uppercase-start typedefs or tagged types, so control-flow
    # (`if (x) {`) never matches.
    clit_pat = re.compile(r"\(\s*(?:struct\s+|union\s+|enum\s+)?[A-Z][A-Za-z0-9_]*\s*\)[ \t]*\{" )
    extras = []
    clit_files = set()
    for top in ("game", "platform"):
        for dirpath, dirnames, filenames in os.walk(os.path.join(out, top)):
            dirnames[:] = [d for d in dirnames if d != ".git"]
            for fn in filenames:
                if not fn.endswith((".c", ".inc")):
                    continue
                p = os.path.join(dirpath, fn)
                rel = rel_norm(os.path.relpath(p, out))
                if rel in targets_set:
                    continue
                txt = b2s(read_bytes(p))
                if macro_pat.search(txt):
                    extras.append(rel)
                    continue
                if clit_pat.search(txt):
                    clit_files.add(rel)
    if extras:
        log("macro-only files (dissolve pass): %d" % len(extras))
        for e_ in extras:
            log("  %s" % e_)
    if clit_files:
        log("compound-literal files (AST pass): %d" % len(clit_files))
        for e_ in sorted(clit_files):
            log("  %s" % e_)

    units = {}   # unit -> [files]
    unity_txt = b2s(read_bytes(os.path.join(out, "game", "game_unity.h")))
    inc233 = re.findall(r'#include\s+"(233/[^"]+)"', unity_txt)

    all_files = sorted(targets_set | set(extras) | clit_files)
    default_files = []
    for t in all_files:
        if t.startswith("game/230/"):
            units.setdefault("game/230.c", []).append(t)
        elif t.startswith("game/233/"):
            pass  # handled below
        else:
            default_files.append(t)

    t233 = [t for t in all_files if t.startswith("game/233/")]
    if t233:
        wrapper = os.path.join(out, "game", "_unit233.c")
        body = "#include <common.h>\n" + "".join('#include "%s"\n' % p for p in inc233)
        write_bytes(wrapper, s2b(body))
        units["game/_unit233.c"] = t233
        log("233 wrapper unit includes: %s" % ", ".join(inc233))

    for t in default_files:
        units.setdefault(t, []).append(t)

    # 5. dump + transform
    ctx = Ctx(out)
    report = {"files": {}, "skipped": {}, "unions": {}, "fixups": []}
    fixups_all = []
    for unit, file_list, dump in dump_units_batched(sorted(units.items()), out, args.clang, log):
        if dump is None:
            continue
        for target in file_list:
            log("== transform: %s%s" % (target, "" if target in targets_set else "  (macro/literal-only)"))
            edits, skipped, unions, fixups = collect_edits_for_file(
                dump, rel_norm(target), ctx, log, args.debug_print,
                macro_only=(target not in targets_set))
            if skipped:
                log("   skipped %d list(s): %s" % (len(skipped), ", ".join(str(s[1]) for s in skipped[:10])))
            for t_ in sorted(set(u[0] for u in unions)):
                log("   union lists seen: %s" % t_)
            p = os.path.join(out, target)
            buf = read_bytes(p)
            if edits:
                buf = apply_edits(buf, edits, log, target)
                write_bytes(p, buf)
                ctx.forget(rel_norm(target))
            report["files"][target] = {"rewritten": len(edits)}
            report["skipped"][target] = [[s[0], s[1]] for s in skipped]
            report["unions"][target] = sorted(set(u[0] for u in unions))
            fixups_all.extend(fixups)

    # 5b. generated runtime fixups for non-first union members
    if fixups_all:
        body = [
            "/* ctr360 - generated file. Do not edit.",
            " * Runtime application of designated union-member initializers that C89 /",
            " * MSVC-2010 (XDK) cannot express positionally (designated member is not",
            " * the union's first member). Values are copied verbatim from the original",
            " * C99 sources. Call Ctr360_ApplyStaticFixups() once at boot, before the",
            " * game reads these tables. */",
            "#include <common.h>",
            "",
            "void Ctr360_ApplyStaticFixups(void)",
            "{",
        ]
        for e in fixups_all:
            body.append("\t%-100s /* %s */" % (e["stmt"], e["file"]))
        body.append("}")
        write_bytes(os.path.join(out, "game", "_ctr360_fixups.c"), s2b("\n".join(body) + "\n"))
        report["fixups"] = [e["stmt"] for e in fixups_all]
        log("generated fixups: %d statement(s) -> game/_ctr360_fixups.c" % len(fixups_all))

    # 5c. C89 declaration hoisting (fresh dumps over every source file)
    if not args.no_hoist:
        hunits = build_hoist_units(out, log)
        if args.hoist_only:
            keep = set(rel_norm(p) for p in args.hoist_only.split(","))
            hunits = {u: [t for t in fl if t in keep] for u, fl in hunits.items()}
            hunits = {u: fl for u, fl in hunits.items() if fl}
        hoist_total, manual = run_hoist_pass(out, hunits, ctx, args.clang, log)
        log("hoist pass: %d edit(s), %d manual-review note(s)" % (hoist_total, len(manual)))
        for n_ in manual[:40]:
            log("  HOIST NOTE %s" % n_)

    # 6. leftover scan + report
    leftovers = scan_designator_lines(out)
    log("leftover designator lines after transform: %d file(s)" % len(leftovers))
    for k, v in sorted(leftovers.items()):
        log("  %s  lines %s%s" % (k, v[:8], " ..." if len(v) > 8 else ""))
    report["leftovers"] = leftovers
    write_bytes(os.path.join(out, "_transform_report.json"),
                json.dumps(report, indent=1, sort_keys=True).encode("utf-8"))

    # 7. optional verify: re-dump every parse unit against the transformed mirror
    if args.verify_syntax:
        bad = run_verify(out, sorted(units), args.clang, log)
        log("unit verify: %d failure(s)" % bad)

    wrapper = os.path.join(out, "game", "_unit233.c")
    if os.path.exists(wrapper):
        os.remove(wrapper)

    try:
        os.remove(lockp)
    except OSError:
        pass

    # 6. mechanical C89 pass LAST: the hoist pass rebuilds files through clang, which
    # prints C99 "inline" for __inline, and the XDK C compiler rejects it (C2054).
    apply_text_transforms(out, log)

    write_mirror_manifest(root, out)
    log("manifest: %s" % os.path.join(out, MIRROR_MANIFEST))

    log("done. report: %s" % os.path.join(out, "_transform_report.json"))
    return 0 if not leftovers else 2

if __name__ == "__main__":
    sys.exit(main())

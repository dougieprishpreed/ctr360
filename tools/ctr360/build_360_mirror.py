def scan_designator_lines(mirror):
    """Find designator-like syntax in initializer contexts, anywhere on a line
    (`.field =` / `[idx] =` preceded by '{' or ','), with comments blanked out.
    Returns {relpath: [(line, snippet), ...]}."""
    pat = re.compile(r"[{,]\s*(?:\.[A-Za-z_][A-Za-z0-9_]*|\[[^\]\n]*\])\s*=[^=]")
    comment = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
    hits = {}
    for dirpath, dirnames, filenames in os.walk(mirror):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for fn in filenames:
            if not fn.endswith((".c", ".h", ".inc")):
                continue
            p = os.path.join(dirpath, fn)
            rel = rel_norm(os.path.relpath(p, mirror))
            raw = b2s(read_bytes(p))
            clean = comment.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), raw)
            found = []
            for m in pat.finditer(clean):
                line = clean[:m.start()].count("\n") + 1
                found.append((line, raw[m.start(): m.start() + 48].replace("\n", " ")))
            if found:
                hits[rel] = found
    return hits


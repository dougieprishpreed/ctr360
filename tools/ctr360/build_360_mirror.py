# ------------------------------------------------------------------ utilities

def b2s(b):
    return b.decode("latin-1")

def s2b(s):
    return s.encode("latin-1")

def read_bytes(p):
    with open(p, "rb") as f:
        return f.read()

def write_bytes(p, b):
    d = os.path.dirname(p)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(p, "wb") as f:
        f.write(b)

def rel_norm(p):
    return os.path.normpath(p).replace("\\", "/").lower()

def loc_norm(f):
    return rel_norm(f) if f else None

def copy_tree(src, dst):
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for fn in filenames:
            s = os.path.join(dirpath, fn)
            r = os.path.relpath(s, src)
            write_bytes(os.path.join(dst, r), read_bytes(s))

# The mirror is a disposable build input.  Keep a content-addressed record of
# both sides so build_xex.sh can reject an old or hand-edited tree without
# having to regenerate it first.
MIRROR_MANIFEST = "_ctr360_mirror_manifest.json"
MANIFEST_SOURCE_DIRS = ("game", "include", "platform")

def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()

def tree_hashes(root, dirs):
    """Return every regular file below dirs, keyed relative to root."""
    found = {}
    for top in dirs:
        base = os.path.join(root, top)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if d != ".git"]
            for fn in sorted(filenames):
                path = os.path.join(dirpath, fn)
                if os.path.isfile(path):
                    found[os.path.relpath(path, root).replace("\\", "/")] = sha256_file(path)
    return dict(sorted(found.items()))

def write_mirror_manifest(root, out):
    generator = os.path.abspath(__file__)
    try:
        commit = subprocess.check_output(
            ["git", "-C", root, "rev-parse", "HEAD"], stderr=subprocess.DEVNULL
        ).decode("ascii").strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None

    generated = tree_hashes(out, MANIFEST_SOURCE_DIRS)
    # These are generated by this tool and are consumed by diagnostics/builds.
    for name in ("_transform_report.json", "game/_ctr360_fixups.c"):
        path = os.path.join(out, *name.split("/"))
        if os.path.isfile(path):
            generated[name] = sha256_file(path)
    manifest = {
        "format": 1,
        "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat(),
        "source_commit": commit,
        "generator": "tools/ctr360/build_360_mirror.py",
        "generator_sha256": sha256_file(generator),
        "authoritative_files": tree_hashes(root, MANIFEST_SOURCE_DIRS),
        "generated_files": dict(sorted(generated.items())),
    }
    write_bytes(os.path.join(out, MIRROR_MANIFEST),
                (json.dumps(manifest, indent=1, sort_keys=True) + "\n").encode("utf-8"))

# ------------------------------------------------------------------ macro patches

def find_define_block(text, name):
    lines = text.splitlines(keepends=True)
    for i, ln in enumerate(lines):
        if re.match(r"[ \t]*#\s*define\s+%s\b" % re.escape(name), ln):
            j = i
            while lines[j].rstrip("\r\n").endswith("\\"):
                j += 1
                if j >= len(lines):
                    raise RuntimeError("unterminated macro: " + name)
            start = sum(len(x) for x in lines[:i])
            end = sum(len(x) for x in lines[: j + 1])
            return text[start:end], start, end
    raise KeyError("macro not found: " + name)

def insert_macro_pads(text, name, marker_fragment, pads):
    """Insert explicit zero pads before the macro line containing
    marker_fragment. Designated initializers may skip struct members; the
    positionally rewritten macro cannot, so skipped slots need explicit lines
    (one per skipped member; {0} for aggregates, 0 for scalars)."""
    old, s, e = find_define_block(text, name)
    eol = "\r\n" if "\r\n" in old else "\n"
    lines = old.splitlines(keepends=True)
    out = []
    done = False
    for ln in lines:
        if not done and marker_fragment in ln:
            for pad in pads:
                out.append(pad + " \\" + eol)
            done = True
        out.append(ln)
    if not done:
        raise RuntimeError("pad marker not found in macro " + name)
    return text[:s] + "".join(out) + text[e:]


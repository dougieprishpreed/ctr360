def apply_header_patches(mirror, log):
    NL = chr(10)
    for path, needle, repl, note in HEADER_PATCHES:
        p = os.path.join(mirror, path)
        t = b2s(read_bytes(p))
        rx = ("[" + chr(13) + "]?" + NL).join(re.escape(line) for line in needle.split(NL))
        use_crlf = (chr(13) + NL) in t
        repl_text = repl.replace(NL, chr(13) + NL) if use_crlf else repl
        # Idempotence: a re-run over an already-patched mirror must not re-apply
        # an insertion-only patch (its needle stays valid after application).
        if (needle in t) and all((line in t) for line in repl.split(NL) if line.strip()):
            log("skip %s: %s (already applied)" % (path, note))
            continue
        t2, n = re.subn(rx, repl_text, t, count=1)
        if n != 1:
            # Idempotence for replace-style patches: needle gone, tail present.
            tail = repl.split(NL)[-1]
            if (needle not in t) and (tail in t):
                log("skip %s: %s (already applied)" % (path, note))
                continue
            raise RuntimeError("header patch failed in %s: %s (%d matches)" % (path, note, n))
        write_bytes(p, s2b(t2))
        log("patched %s: %s" % (path, note))


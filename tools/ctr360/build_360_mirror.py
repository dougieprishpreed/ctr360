def apply_text_transforms(mirror, log):
    """Mechanical C89-ification over every mirrored source file:
       - inline -> __inline (the XDK compiler has no C99 'inline' in C mode)
       - stdbool.h shim written into include/ (no stdbool.h in the XDK CRT)."""
    changed = 0
    for dirpath, dirnames, filenames in os.walk(mirror):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for fn in filenames:
            if not fn.endswith((".c", ".h", ".inc")):
                continue
            p = os.path.join(dirpath, fn)
            raw = b2s(read_bytes(p))
            new = re.sub(r"\binline\b", "__inline", raw)
            if new != raw:
                write_bytes(p, s2b(new))
                changed += 1
    write_bytes(os.path.join(mirror, "include", "stdbool.h"), s2b(STDBOOL_SHIM_TEXT))
    log("text transforms: inline -> __inline in %d file(s); stdbool.h shim written" % changed)

